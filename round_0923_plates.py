def git(*args, stdin=None):
    return subprocess.run(["git", *args], input=stdin, capture_output=True, text=True)


if git("rev-parse", "--show-toplevel").returncode:
    sys.exit("Run this from inside the repo folder.")
with tempfile.NamedTemporaryFile("w", suffix=".diff", delete=False) as f:
    f.write(DIFF)
    path = f.name
try:
    if git("apply", "--reverse", "--check", path).returncode == 0:
        print("Already applied; nothing to do.")
        sys.exit(0)
    chk = git("apply", "--check", path)
    if chk.returncode:
        print(chk.stderr.strip())
        sys.exit("Does not apply cleanly. No earlier patch is needed. Run git pull first; if it still refuses, the files changed since this was built.")
    res = git("apply", path)
    if res.returncode:
        sys.exit(res.stderr.strip())
    print("Applied. Changed:")
    for line in DIFF.splitlines():
        if line.startswith("+++ b/"):
            print("  " + line[6:])
finally:
    os.unlink(path)
